function triggerCreditsSequence(onComplete) {
    const track = document.getElementById('credits-track');
    const viewport = document.getElementById('credits-viewport');
    if (!track || !viewport) return;

    track.innerHTML = '';
    track.className = 'credits-crawl-track';

    CODEX_CREDITS.forEach(item => {
        const div = document.createElement('div');
        div.innerHTML = item;
        track.appendChild(div);
    });

    const viewportHeight = viewport.offsetHeight;
    const trackHeight = track.scrollHeight;
    
    track.style.transform = `translateY(${viewportHeight}px)`;

    setTimeout(() => {
        track.classList.add('crawl-slow');
        track.style.transform = `translateY(${viewportHeight - 120}px)`;

        setTimeout(() => {
            playAudio(BOSS_AUDIO_PATHS.rewindSound);
            track.classList.remove('crawl-slow');
            track.classList.add('crawl-warp');
            track.style.transform = `translateY(-${trackHeight + 80}px)`;

            setTimeout(() => {
                const endScreen = document.getElementById('ending-screen');
                if (endScreen) endScreen.style.opacity = '0';

                setTimeout(() => {
                    const bellEl = document.getElementById('end-record-final');
                    if (bellEl) bellEl.classList.add('active');
                    playAudio(BOSS_AUDIO_PATHS.bellSound);

                    if (onComplete) onComplete();
                }, 350);
            }, 2000);
        }, 1000);
    }, 100);
}